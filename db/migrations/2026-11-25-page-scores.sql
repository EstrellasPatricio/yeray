-- Tareas #29 y #30: tabla de puntuaciones de peligrosidad de las páginas.
-- Solo para bases de datos que ya tenían aplicado db/schema.sql antes de este cambio.
-- En un proyecto nuevo basta con ejecutar db/schema.sql, que ya la incluye.

CREATE TABLE IF NOT EXISTS page_scores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_id INTEGER NOT NULL REFERENCES domains(id),
  score SMALLINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_page_scores_score CHECK (score BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_page_scores_domain_created_at ON page_scores (domain_id, created_at);
