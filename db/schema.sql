-- ---------------------------------------------------------------------
-- ENUMS
-- ---------------------------------------------------------------------

CREATE TYPE risk_level AS ENUM (
  'safe',       -- segura
  'suspicious', -- sospechosa
  'malicious',  -- maliciosa
  'unknown'     -- sin veredicto (fuente no disponible)
);

CREATE TYPE analysis_source AS ENUM (
  'virustotal',
  'ai_text',          -- detección de ingeniería social (NLP)
  'dom_structure',    -- DOM / HTML / scripts
  'url_analysis',     -- ofuscación, dominios sospechosos
  'cookies',
  'gdpr',
  'trustpilot',
  'community_reviews'
);

CREATE TYPE source_status AS ENUM (
  'ok',
  'degraded',
  'unavailable',
  'quota_exhausted',  -- 429 / límite diario
  'timeout',
  'malformed_response'
);

CREATE TYPE exception_scope AS ENUM (
  'exact_host',
  'host_and_subdomains'
);

CREATE TYPE cookie_phase AS ENUM (
  'before_consent',
  'after_consent'
);

-- ---------------------------------------------------------------------
-- USUARIOS Y SESIONES (HU#9, #10, #14, #17, #18)
-- ---------------------------------------------------------------------

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL, -- hash con sal
  public_alias VARCHAR(40),            -- alias mostrado en reseñas públicas; evita exponer email
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP,
  deleted_at TIMESTAMP                 -- eliminación lógica (HU#17)
);

CREATE UNIQUE INDEX uq_users_email_active ON users (lower(email)) WHERE deleted_at IS NULL;

CREATE TABLE sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  token_hash VARCHAR(128) NOT NULL UNIQUE, -- se guarda el hash del token, no el token
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP NOT NULL,           -- según el plazo elegido (HU#10)
  last_used_at TIMESTAMP,
  revoked_at TIMESTAMP                     -- cierre de sesión (HU#18)
);

CREATE INDEX idx_sessions_user_revoked ON sessions (user_id, revoked_at);

CREATE TABLE password_reset_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  token_hash VARCHAR(128) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP NOT NULL,
  used_at TIMESTAMP                        -- un solo uso (HU#9)
);

-- ---------------------------------------------------------------------
-- DOMINIOS, EXCEPCIONES Y LISTA DE RIESGO COMPARTIDA (HU#3)
-- ---------------------------------------------------------------------

CREATE TABLE domains (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host VARCHAR(253) NOT NULL UNIQUE, -- host normalizado
  first_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE domain_exceptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  domain_id INTEGER NOT NULL REFERENCES domains(id),
  scope exception_scope NOT NULL DEFAULT 'exact_host',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_domain_exceptions_user_domain_scope UNIQUE (user_id, domain_id, scope)
);

-- ---------------------------------------------------------------------
-- RESEÑAS (HU#4)
-- ---------------------------------------------------------------------

CREATE TABLE reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  domain_id INTEGER NOT NULL REFERENCES domains(id),
  rating SMALLINT NOT NULL,
  comment VARCHAR(1000), -- opcional; validar longitud en cliente y servidor
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP,
  CONSTRAINT ck_rating_range CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT uq_reviews_user_domain UNIQUE (user_id, domain_id)
);

CREATE INDEX idx_reviews_domain_id ON reviews (domain_id);

-- ---------------------------------------------------------------------
-- PUNTUACIÓN DE PELIGROSIDAD DE LA PÁGINA (tareas #29 y #30)
-- ---------------------------------------------------------------------

-- Una fila por puntuación enviada desde el formulario de reporte (0 = segura, 100 = muy peligrosa).
-- Solo se guarda el dominio y la puntuación; sin usuario hasta que exista el login.
CREATE TABLE page_scores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_id INTEGER NOT NULL REFERENCES domains(id),
  score SMALLINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_page_scores_score CHECK (score BETWEEN 0 AND 100)
);

CREATE INDEX idx_page_scores_domain_created_at ON page_scores (domain_id, created_at);

-- ---------------------------------------------------------------------
-- CUOTAS DE APIs EXTERNAS (HU#5, HU#11, RNF02)
-- ---------------------------------------------------------------------

CREATE TABLE api_quota_usage (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider analysis_source NOT NULL, -- virustotal / trustpilot (OpenWeb Ninja)
  period_start DATE NOT NULL,
  period_duration VARCHAR(10) NOT NULL, -- en minutos
  requests_used INTEGER NOT NULL DEFAULT 0,
  request_limit INTEGER NOT NULL
);

-- ---------------------------------------------------------------------
-- ANÁLISIS E INFORME VISUAL (HU#6, #11, #13, #19, #20)
-- ---------------------------------------------------------------------

CREATE TABLE analyses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_id INTEGER NOT NULL REFERENCES domains(id),
  url TEXT NOT NULL,                    -- sin query string ni fragmento (minimización de datos)
  global_risk risk_level NOT NULL DEFAULT 'unknown',
  global_score SMALLINT,
  is_degraded BOOLEAN NOT NULL DEFAULT FALSE, -- alguna fuente no disponible
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_global_score CHECK (global_score IS NULL OR global_score BETWEEN 0 AND 100)
);

CREATE INDEX idx_analyses_domain_created_at ON analyses (domain_id, created_at);

CREATE TABLE user_history (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  analysis_id INTEGER NOT NULL REFERENCES analyses(id),
  viewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, analysis_id) -- un registro por usuario y análisis; actualizar viewed_at al volver a consultarlo
);

CREATE INDEX idx_user_history_user_viewed_at ON user_history (user_id, viewed_at);

CREATE TABLE analysis_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_id INTEGER NOT NULL REFERENCES analyses(id),
  source analysis_source NOT NULL,
  status source_status NOT NULL DEFAULT 'ok',
  verdict risk_level NOT NULL DEFAULT 'unknown',
  score SMALLINT,
  confidence DECIMAL(4, 3), -- 0.000 - 1.000 (modelo de IA)
  summary TEXT,
  detail_url TEXT,          -- enlace al detalle (p. ej. informe VirusTotal)
  model_version VARCHAR(50),
  raw_payload JSON,         -- respuesta cruda opcional, para depuración
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_analysis_results_analysis_source UNIQUE (analysis_id, source)
);

-- ---------------------------------------------------------------------
-- [AMPLIACIÓN] COOKIES Y RASTREADORES (HU#7)
-- ---------------------------------------------------------------------

CREATE TABLE cookie_findings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_id INTEGER NOT NULL REFERENCES analyses(id),
  phase cookie_phase NOT NULL,
  name VARCHAR(200) NOT NULL,
  cookie_domain VARCHAR(253) NOT NULL,
  is_third_party BOOLEAN NOT NULL DEFAULT FALSE,
  secure BOOLEAN,
  http_only BOOLEAN,
  same_site VARCHAR(10) -- strict | lax | none
);